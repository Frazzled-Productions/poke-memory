// Writes db/d1/migrations/0002_auth.sql: Better Auth's tables as the installed
// better-auth generates them for SQLite with the username plugin (decision
// 0018, design D6), followed by the hand-written username format triggers.
//
//   node scripts/cloudflare/generate-auth-migration.mjs          write the file
//   node scripts/cloudflare/generate-auth-migration.mjs --check  exit 1 if stale
//
// The schema only depends on the plugins, not on secrets or providers. If
// lib/auth adds a plugin that adds tables or columns, add it to PLUGINS here
// and put the difference in a NEW migration (0002 may already be applied).
// lib/db/authMigration.test.ts runs --check so a better-auth upgrade that
// changes the schema fails CI instead of drifting.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DatabaseSync } from "node:sqlite";
import { getMigrations } from "better-auth/db/migration";
import { username } from "better-auth/plugins";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const AUTH_MIGRATION = path.join(root, "db/d1/migrations/0002_auth.sql");
const BEGIN = "-- BEGIN generated by better-auth";
const END = "-- END generated by better-auth";

const PLUGINS = [username()];

export async function generatedAuthSql() {
  const { compileMigrations } = await getMigrations({
    database: new DatabaseSync(":memory:"),
    // Placeholders: getMigrations reads only the schema, never these.
    secret: "schema-generation-placeholder-not-a-secret",
    baseURL: "http://localhost",
    emailAndPassword: { enabled: true },
    plugins: PLUGINS,
  });
  const sql = (await compileMigrations()).trim();
  return sql.endsWith(";") ? sql : `${sql};`;
}

const HEADER = `-- Better Auth tables for Cloudflare D1 (decision 0018, design D6), with the
-- username plugin. The block between the markers is generated by
-- scripts/cloudflare/generate-auth-migration.mjs from the installed
-- better-auth; do not edit it by hand. Better Auth's own queries run inside
-- the library (outside lib/db/scope.ts and the scoped-queries rule).
--
-- User ids are UUIDs (generateId in lib/auth), the same shape as the ids
-- copied from Supabase, so the app tables' user_id keeps its meaning.
`;

const USERNAME_RULES = `-- Username format (Postgres usernames table, 035): lower case, 3 to 30 of
-- a-z 0-9 _ -. Null for accounts without a username (GitHub, Google).
CREATE TRIGGER user_username_format_insert
BEFORE INSERT ON "user"
FOR EACH ROW
WHEN NEW.username IS NOT NULL
BEGIN
  SELECT RAISE(ABORT, 'check_violation: username must be 3 to 30 characters of a-z, 0-9, _ or -')
    WHERE length(NEW.username) NOT BETWEEN 3 AND 30
       OR NEW.username GLOB '*[^a-z0-9_-]*';
END;

CREATE TRIGGER user_username_format_update
BEFORE UPDATE OF username ON "user"
FOR EACH ROW
WHEN NEW.username IS NOT NULL
BEGIN
  SELECT RAISE(ABORT, 'check_violation: username must be 3 to 30 characters of a-z, 0-9, _ or -')
    WHERE length(NEW.username) NOT BETWEEN 3 AND 30
       OR NEW.username GLOB '*[^a-z0-9_-]*';
END;
`;

export async function renderAuthMigration() {
  return `${HEADER}\n${BEGIN}\n${await generatedAuthSql()}\n${END}\n\n${USERNAME_RULES}`;
}

/** The generated block of an existing file, or null when the markers are missing. */
export function generatedBlockOf(text) {
  const start = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (start < 0 || end < start) return null;
  return text.slice(start + BEGIN.length, end).trim();
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(AUTH_MIGRATION) ? fs.readFileSync(AUTH_MIGRATION, "utf8") : "";
    if (generatedBlockOf(current) !== (await generatedAuthSql())) {
      console.error(
        "db/d1/migrations/0002_auth.sql no longer matches the installed better-auth schema. " +
          "Put the difference in a new migration (0002 may already be applied).",
      );
      process.exit(1);
    }
    console.log("0002_auth.sql matches the installed better-auth schema.");
  } else {
    fs.writeFileSync(AUTH_MIGRATION, await renderAuthMigration());
  }
}
