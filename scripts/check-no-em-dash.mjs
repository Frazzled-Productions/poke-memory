#!/usr/bin/env node
// Regression guard for the no-em-dash rule (`ops/standards/conventions.md` ->
// Writing; house directive 2026-06-03: no em dashes anywhere). An em dash
// (U+2014) must not appear in any text the project authors. This script is
// wired into CI (`npm run lint` in the `test` job, plus ci.yml's always-run
// `em-dash` job so docs-only PRs are gated too, #2134) so the rule is enforced
// on every PR rather than relying on review alone.
//
// SCOPE: every git-tracked file (`git ls-files`), so node_modules, .next,
// build output and anything gitignored are never considered. Files are routed
// by type:
//   - JS/TS source (.ts/.tsx/.mjs/.cjs/.js, anywhere in the repo, including
//     root configs and .github/scripts): parsed, and every comment, JSX text
//     node and string / template literal is checked.
//   - Everything else that is text (Markdown, YAML workflows and issue
//     templates, shell, SQL, CSS, JSON message catalogues, SVG, Python,
//     LICENSE, .example files, snapshots, ...): every line is checked. There is
//     no front-matter or docs exemption.
//   - Binary files (known media/font extensions, or any file whose first 8000
//     bytes contain a NUL byte, git's own heuristic) are skipped.
//
// Only U+2014 is flagged. Other dashes (U+2013 en dash, U+2015 horizontal bar,
// U+2212 minus) are out of scope; a zh/ja catalogue that needs a long CJK dash
// must use U+2015, not a doubled U+2014.
//
// ALLOWED:
//   - the standalone "no value" dash glyph in JS/TS source. That glyph is an
//     em dash used on its own as a placeholder (e.g. RecordsCard,
//     AccuracySparkline, HigherOrLowerGame) and as the literal matched by tests
//     (getAllByText, not.toContain). A string or JSX text node whose only
//     non-whitespace content is the dash is allowed; an em dash embedded in a
//     longer run is flagged. Plain-text files get no such allowance.
//   - paths in EXCLUDED_PATHS below, each with its reason. The house rule's
//     only exception, an external identifier that literally contains an em
//     dash, belongs there too (none exist today).
//
// Run directly: `node scripts/check-no-em-dash.mjs` (or `npm run lint:em-dash`).
// Exit code 0 = clean, 1 = at least one violation.

import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const EM_DASH = "—";
const REPO_ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));

// This detector file necessarily contains the em-dash glyph (the EM_DASH
// constant above and the header comment). Exclude it from scanning so the
// linter never flags itself. Compared against the repo-relative path.
const DETECTOR_SELF_PATH = relative(
  REPO_ROOT,
  fileURLToPath(import.meta.url),
).replace(/\\/g, "/");

// File extensions parsed as source (TypeScript, TSX, and the .mjs/.js/.cjs
// scripts). The TypeScript parser handles all of these.
const SOURCE_EXT = /\.(tsx?|mjs|cjs|js)$/;

// Known binary extensions, skipped without reading (the repo tracks ~15k
// sprites and cries). Anything else is sniffed for a NUL byte.
const BINARY_EXT =
  /\.(png|webp|jpe?g|gif|ico|avif|bmp|mp3|ogg|wav|m4a|mp4|webm|woff2?|ttf|otf|eot|pdf|zip|gz|tgz)$/i;

// Paths never scanned. Each entry is an exact repo-relative path or, when it
// ends in `/`, a directory prefix. Every entry carries its reason.
const EXCLUDED_PATHS = [
  // Lockfile: machine-written third-party package metadata, not authored text.
  "package-lock.json",
  // Seed output generated by scripts/seed-pokemon.mjs from PokéAPI: species
  // names and flavour text are verbatim third-party copy (which does use em
  // dashes). Regenerated wholesale on every re-seed, so edits would not stick.
  "lib/pokemon/generated.json",
  "lib/pokemon/generated-chains.json",
  "lib/pokemon/generated-core.json",
  "lib/pokemon/generated-flavor.json",
  "lib/pokemon/generated-locale-names.json",
  "public/pokemon-data/",
  // Generated from messages/en.json by `npm run generate:pseudo-locale`; the
  // source catalogue is scanned, and lint:pseudo-locale enforces parity.
  "messages/xx-pseudo.json",
];

function isExcluded(relPath) {
  return EXCLUDED_PATHS.some((entry) =>
    entry.endsWith("/") ? relPath.startsWith(entry) : relPath === entry,
  );
}

/**
 * Route a repo-relative path to its scanner: "source" (parsed JS/TS), "text"
 * (line scan), or "skip" (excluded, the detector itself, or a known binary).
 * Files routed to "text" are still sniffed for binary content before scanning.
 */
function classify(relPath) {
  if (relPath === DETECTOR_SELF_PATH || isExcluded(relPath)) return "skip";
  if (BINARY_EXT.test(relPath)) return "skip";
  if (SOURCE_EXT.test(relPath)) return "source";
  return "text";
}

/**
 * Strip a single layer of matching surrounding quote characters (`"`, `'` or
 * a backtick) from a string. `node.getText(sourceFile)` returns a string
 * literal *with* its quotes (`"—"`), whereas a JSX text node's `.text` is
 * already unquoted. Normalising here lets `isStandaloneNoValueGlyph` treat
 * both call-site shapes identically.
 */
function stripSurroundingQuotes(text) {
  if (text.length >= 2) {
    const first = text[0];
    const last = text[text.length - 1];
    if (first === last && (first === '"' || first === "'" || first === "`")) {
      return text.slice(1, -1);
    }
  }
  return text;
}

/**
 * True when a string's only non-whitespace content is em dashes. That is the
 * intentional "no value" placeholder glyph and must not be flagged. An em dash
 * sitting inside other prose is a real violation.
 *
 * Accepts either an unquoted value (a JSX text node's `.text`) or a quoted
 * string-literal source (`node.getText(sourceFile)`); surrounding quotes are
 * stripped first so an `alt` value and a bare text node behave the same.
 */
function isStandaloneNoValueGlyph(text) {
  const unquoted = stripSurroundingQuotes(text);
  return (
    unquoted.includes(EM_DASH) &&
    unquoted.replace(new RegExp(`[\\s${EM_DASH}]`, "g"), "") === ""
  );
}

function recordViolation(sink, file, sourceFile, pos, context) {
  const { line, character } = sourceFile.getLineAndCharacterOfPosition(pos);
  sink.push({
    file: relative(REPO_ROOT, file),
    line: line + 1,
    column: character + 1,
    context: context.trim().replace(/\s+/g, " ").slice(0, 120),
  });
}

function recordRawViolation(sink, file, line, column, context) {
  sink.push({
    file: relative(REPO_ROOT, file),
    line,
    column,
    context: context.trim().replace(/\s+/g, " ").slice(0, 120),
  });
}

/**
 * Find every comment range (`//` line, `/* *\/` block, JSDoc, and JSX `{/* *\/}`)
 * in raw source text with a small character scanner that skips over string,
 * template and regex literals so a `//` *inside* a string is never mistaken for
 * a comment. The TypeScript scanner mis-tokenises trivia inside JSX regions of a
 * `.tsx` file, so this raw pass is used for comments instead of `ts`.
 *
 * Returns `[start, end]` half-open offsets into `text`.
 */
function commentRanges(text) {
  const ranges = [];
  const n = text.length;
  let i = 0;
  // The previous significant (non-whitespace) character, used to decide whether
  // a `/` opens a regex literal (it does after an operator / `(` / `,` etc.).
  let prevSig = "";
  while (i < n) {
    const c = text[i];
    const d = text[i + 1];
    if (c === "/" && d === "/") {
      const start = i;
      i += 2;
      while (i < n && text[i] !== "\n") i++;
      ranges.push([start, i]);
      prevSig = "";
      continue;
    }
    if (c === "/" && d === "*") {
      const start = i;
      i += 2;
      while (i < n && !(text[i] === "*" && text[i + 1] === "/")) i++;
      i = Math.min(i + 2, n);
      ranges.push([start, i]);
      prevSig = "";
      continue;
    }
    if (c === '"' || c === "'") {
      i++;
      while (i < n && text[i] !== c) {
        if (text[i] === "\\") i++;
        i++;
      }
      i++;
      prevSig = c;
      continue;
    }
    if (c === "`") {
      i++;
      while (i < n && text[i] !== "`") {
        if (text[i] === "\\") {
          i++;
        } else if (text[i] === "$" && text[i + 1] === "{") {
          // Skip a `${ ... }` interpolation, tracking nested braces.
          let depth = 1;
          i += 2;
          while (i < n && depth > 0) {
            if (text[i] === "{") depth++;
            else if (text[i] === "}") depth--;
            i++;
          }
          continue;
        }
        i++;
      }
      i++;
      prevSig = "`";
      continue;
    }
    if (c === "/" && /[=(,:;[{!&|?+\-*%^~]/.test(prevSig)) {
      // Regex literal: opens after an operator or opening bracket. `<` and `>`
      // are deliberately excluded: in a `.tsx` file a `/` after `<` or `>` is a
      // JSX close tag (`</div>`) far more often than a regex, and treating it as
      // a regex would swallow a following `// comment` (see the JSX edge case in
      // the gate's test). A genuine regex opening right after a `<`/`>` operator
      // does not occur in this repo.
      i++;
      let inClass = false;
      while (i < n) {
        const r = text[i];
        if (r === "\\") {
          i += 2;
          continue;
        }
        if (r === "[") inClass = true;
        else if (r === "]") inClass = false;
        else if (r === "/" && !inClass) {
          i++;
          break;
        } else if (r === "\n") break;
        i++;
      }
      prevSig = "/";
      continue;
    }
    if (!/\s/.test(c)) prevSig = c;
    i++;
  }
  return ranges;
}

/**
 * Scan a file's comments (single-line, multi-line, JSDoc, JSX comments) for em
 * dashes. Comments are prose: every em dash in one is a violation (no glyph
 * exemption).
 */
function scanComments(sink, file, text, sourceFile) {
  for (const [start, end] of commentRanges(text)) {
    const tokenText = text.slice(start, end);
    if (tokenText.includes(EM_DASH)) {
      recordViolation(sink, file, sourceFile, start, tokenText);
    }
  }
}

/**
 * Walk the AST flagging em dashes in JSX text and in every string / template
 * literal (test labels, script output, JSX props, metadata, anything). The
 * standalone no-value glyph is allowed in both shapes.
 */
function scanAst(sink, file, sourceFile) {
  const visit = (node) => {
    // JSX text nodes - rendered prose. A standalone no-value dash is allowed.
    if (ts.isJsxText(node)) {
      if (node.text.includes(EM_DASH) && !isStandaloneNoValueGlyph(node.text)) {
        recordViolation(sink, file, sourceFile, node.getStart(sourceFile), node.text);
      }
    }

    // Every string / template literal. Covers describe/it labels, script
    // output strings, user-visible JSX props, metadata exports - all of it.
    if (
      ts.isStringLiteral(node) ||
      ts.isNoSubstitutionTemplateLiteral(node) ||
      ts.isTemplateExpression(node)
    ) {
      const raw = node.getText(sourceFile);
      if (raw.includes(EM_DASH) && !isStandaloneNoValueGlyph(raw)) {
        recordViolation(sink, file, sourceFile, node.getStart(sourceFile), raw);
      }
    }

    node.forEachChild(visit);
  };
  visit(sourceFile);
}

/**
 * Scan a single in-memory source text and return its violations. Pure: no
 * filesystem access, no `process.exit`. `fileName` only labels output and
 * selects TSX vs TS parsing. Exported for the forcing-function test.
 */
function scanText(fileName, text) {
  const sink = [];
  if (!text.includes(EM_DASH)) return sink;
  const scriptKind = fileName.endsWith(".tsx")
    ? ts.ScriptKind.TSX
    : ts.ScriptKind.TS;
  const sourceFile = ts.createSourceFile(
    fileName,
    text,
    ts.ScriptTarget.Latest,
    /* setParentNodes */ true,
    scriptKind,
  );
  scanComments(sink, fileName, text, sourceFile);
  scanAst(sink, fileName, sourceFile);
  return sink;
}

/**
 * Line scan for every non-JS/TS text file (Markdown, YAML, shell, SQL, CSS,
 * JSON, ...). Pure: no filesystem access. Every line containing an em dash is
 * one violation. Exported for the forcing-function test.
 */
function scanPlainText(fileName, text) {
  const sink = [];
  if (!text.includes(EM_DASH)) return sink;
  text.split(/\r?\n/).forEach((line, idx) => {
    const col = line.indexOf(EM_DASH);
    if (col !== -1) recordRawViolation(sink, fileName, idx + 1, col + 1, line);
  });
  return sink;
}

/** git's binary heuristic: a NUL byte in the first 8000 bytes. */
function looksBinary(buf) {
  return buf.subarray(0, 8000).includes(0);
}

/** Every git-tracked file, repo-relative with forward slashes. */
function trackedFiles() {
  const out = execFileSync("git", ["ls-files", "-z"], {
    cwd: REPO_ROOT,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  return out.split("\0").filter(Boolean);
}

/** Scan one repo-relative path, routing it by `classify`. */
function checkFile(sink, relPath) {
  const kind = classify(relPath);
  if (kind === "skip") return;
  const abs = join(REPO_ROOT, relPath);
  let buf;
  try {
    buf = readFileSync(abs);
  } catch {
    // Tracked but deleted in the working tree (e.g. mid-rename): nothing to scan.
    return;
  }
  if (kind === "text" && looksBinary(buf)) return;
  const text = buf.toString("utf8");
  // Cheap pre-filter: nothing to do when the file has no em dash at all.
  if (!text.includes(EM_DASH)) return;
  const found =
    kind === "source" ? scanText(abs, text) : scanPlainText(abs, text);
  for (const v of found) sink.push(v);
}

function run() {
  const violations = [];
  for (const relPath of trackedFiles()) checkFile(violations, relPath);
  violations.sort((a, b) =>
    a.file === b.file ? a.line - b.line : a.file.localeCompare(b.file),
  );
  return violations;
}

function main() {
  const found = run();
  if (found.length === 0) {
    console.log("no-em-dash guard: OK (no em dashes in tracked text files).");
    process.exit(0);
  }

  console.error(
    `no-em-dash guard: ${found.length} violation(s) found.\n` +
      `An em dash (U+2014) is not allowed in any authored text: source, comments,\n` +
      `docs, workflows, scripts, SQL, CSS or UI copy (ops/standards/conventions.md\n` +
      `-> Writing). Restructure the sentence, or use a comma, colon, parentheses,\n` +
      `or a spaced hyphen instead.\n`,
  );
  for (const v of found) {
    console.error(`  ${v.file}:${v.line}:${v.column}  ${v.context}`);
  }
  process.exit(1);
}

// Pure helpers exported for the forcing-function test. The CLI entry point
// (`main`) is only invoked when the script is run directly, never on import.
export {
  scanText,
  scanPlainText,
  isStandaloneNoValueGlyph,
  commentRanges,
  classify,
  isExcluded,
  looksBinary,
  run,
  EM_DASH,
  EXCLUDED_PATHS,
};

const INVOKED_DIRECTLY =
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (INVOKED_DIRECTLY) {
  main();
}
