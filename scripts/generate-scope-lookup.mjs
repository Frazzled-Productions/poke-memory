// scripts/generate-scope-lookup.mjs
// Generates lib/pokemon/scopeLookup.ts — a compact, server-importable lookup
// table of the fields needed to evaluate practice-scope predicates server-side
// (daily Web Push route, future server actions).
//
// Only the scope-relevant fields are kept; the full generated.json (~3.8 MB)
// would be too heavy to bundle into an Edge or Node route.
//
// Run with: node scripts/generate-scope-lookup.mjs
//
// Re-run any time generated.json changes (after `npm run seed` or
// `node scripts/seed-version-groups.mjs`).

import { readFile, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const SEED_PATH = resolve(ROOT, "lib/pokemon/generated.json");
const OUT_PATH = resolve(ROOT, "lib/pokemon/scopeLookup.ts");

const seed = JSON.parse(await readFile(SEED_PATH, "utf8"));

/**
 * Compact per-species record. All field names are kept short because this
 * object is iterated at runtime on every cron tick.
 */
const entries = seed.map((p) => ({
  /** Primary pokemon id (same as species id for default forms; 10001+ for alt forms). */
  id: p.id,
  /** Species id (1..1025). Same as id for default forms. */
  speciesId: p.speciesId ?? p.id,
  /** Pokémon types, e.g. ["fire", "flying"]. */
  types: p.types,
  /** True for the primary variety of the species. */
  isDefaultForm: p.isDefaultForm ?? true,
  /** Broad form category. */
  formCategory: p.formCategory ?? "default",
  /** PokéAPI version-group slugs. */
  versionGroups: p.versionGroups ?? [],
  /** Whether the species is legendary (not mythical). */
  isLegendary: p.isLegendary === true,
}));

const ts = `// AUTO-GENERATED by scripts/generate-scope-lookup.mjs — do not edit by hand.
// Re-generate after running \`npm run seed\` or \`node scripts/seed-version-groups.mjs\`.

export type ScopeLookupEntry = {
  id: number;
  speciesId: number;
  types: string[];
  isDefaultForm: boolean;
  formCategory: string;
  versionGroups: string[];
  isLegendary: boolean;
};

// ${entries.length} entries derived from lib/pokemon/generated.json.
export const SCOPE_LOOKUP: readonly ScopeLookupEntry[] = ${JSON.stringify(entries, null, 0)} as const;
`;

await writeFile(OUT_PATH, ts, "utf8");
console.log(`Wrote ${entries.length} entries → ${OUT_PATH}`);
