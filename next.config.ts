import type { NextConfig } from "next";
import createNextIntlPlugin from "next-intl/plugin";
import { withSentryConfig } from "@sentry/nextjs/config";
import pkg from "./package.json";
import { initOpenNextCloudflareForDev } from "@opennextjs/cloudflare";
import { assertMockAuthNotInProduction } from "./lib/auth/mockAuth";

// SECURITY: fail the build loudly if the test-only mock-auth seam (issue #751)
// is enabled in a production build. The seam is already inert in production
// (isMockAuthEnabled() short-circuits on NODE_ENV), so this is defence-in-depth
// - it turns a silent misconfiguration into a hard build failure.
assertMockAuthNotInProduction();

// `next dev` gets the Worker bindings (D1 `DB`, R2 `BACKUPS`, vars) from
// wrangler.jsonc through a local Miniflare, so getCloudflareContext() works in
// dev as it does on Workers (decision 0018). Only in dev: the production build
// and vitest must not start Miniflare.
if (process.env.NODE_ENV === "development") {
  void initOpenNextCloudflareForDev();
}

const nextConfig: NextConfig = {
  // Off for the Cloudflare move (decision 0018, design D1): on
  // @opennextjs/cloudflare every Cache Components page hangs until OpenNext
  // PR #1318 lands (unmerged, and with it a render mismatch is still logged).
  // Turn it back on only once that fix is released and tested on Workers.
  cacheComponents: false,
  env: {
    NEXT_PUBLIC_APP_VERSION: pkg.version ?? "dev",
  },
  // The service worker is not a route: it is built to a static
  // `public/sw/sw.js` asset by `scripts/build-sw.mjs` (post-`next build`) and
  // served from the Worker's static assets (#1752). /whats-new needs no file
  // either: CHANGELOG.md is inlined into a module at build time
  // (scripts/generate-changelog-module.mjs), since Workers have no filesystem.
  // Headers for the statically-generated service-worker script (built to
  // public/sw/ by scripts/build-sw.mjs).
  //
  // - `Cache-Control: no-cache` - the SW spec requires the browser to always
  //   revalidate the worker script before deciding whether to install a new
  //   version; without it, a future edge-cache change could silently freeze
  //   updates for all installed PWAs (#1749).
  // - `Service-Worker-Allowed: /` - the worker is registered from /sw/sw.js but
  //   must claim the whole-site scope "/". The Route Handler previously set this
  //   header itself; for the static asset it is applied here.
  async headers() {
    return [
      {
        source: "/sw/sw.js",
        headers: [
          { key: "Cache-Control", value: "no-cache" },
          { key: "Service-Worker-Allowed", value: "/" },
        ],
      },
      {
        source: "/sw/sw.js.map",
        headers: [{ key: "Cache-Control", value: "no-cache" }],
      },
      // The FSRS optimiser page runs the threaded wasm binding, which needs a
      // shared WebAssembly.Memory and so a cross-origin-isolated page (D7 of
      // openspec/changes/move-to-cloudflare). Only this path is isolated, so
      // cross-origin resources elsewhere keep loading. Link to it with a plain
      // <a>, not next/link: isolation is set per document load.
      {
        source: "/settings/optimiser",
        headers: [
          { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
          { key: "Cross-Origin-Embedder-Policy", value: "require-corp" },
        ],
      },
      // Its worker scripts and wasm (scripts/build-fsrs-optimiser.mjs). A
      // dedicated worker started from an isolated page needs its own COEP.
      // On Workers static assets these come from public/_headers instead,
      // because assets are served before the Next server sees the request.
      {
        source: "/fsrs/:path*",
        headers: [
          { key: "Cross-Origin-Embedder-Policy", value: "require-corp" },
          { key: "Cross-Origin-Resource-Policy", value: "same-origin" },
        ],
      },
    ];
  },
  images: {
    // Custom loader routes sprite paths to pre-generated static WebP files,
    // bypassing the /_next/image optimisation endpoint entirely. GitHub avatar
    // URLs (user-controlled) are passed through unchanged.
    // See lib/sprites/imageLoader.ts for the full routing logic.
    loader: "custom",
    loaderFile: "./lib/sprites/imageLoader.ts",
    // Constrain deviceSizes and imageSizes so their union exactly equals the
    // set of widths pre-generated by `npm run seed:sprites`. The loader snaps
    // any incoming width to the nearest generated width, so Next.js will only
    // ever request widths from this list.
    // Generated widths (from lib/sprites/imageLoaderHelpers.ts):
    //   32, 40, 48, 56, 64, 120, 150, 180, 192, 320
    // Split across deviceSizes (larger) and imageSizes (smaller) as Next.js
    // requires deviceSizes ≥ imageSizes values; the union is what matters.
    deviceSizes: [150, 180, 192, 320],
    imageSizes: [32, 40, 48, 56, 64, 120],
    remotePatterns: [
      {
        // Defence-in-depth: keep the remotePatterns entry for GitHub avatars
        // so the intent is explicit even though remotePatterns is not enforced
        // at runtime when a custom loader is set.
        protocol: "https",
        hostname: "avatars.githubusercontent.com",
      },
    ],
  },
};

// The Serwist service worker is no longer built through a Next.js Route
// Handler, so the `withSerwist` wrapper (which only marked esbuild/esbuild-wasm
// as server-external for that route) is gone. The worker is now bundled to a
// static `public/sw/sw.js` asset by `scripts/build-sw.mjs` after `next build`.
// Offline support for the installed PWA is unchanged, see issues #703, #1752.
//
// `withNextIntl` wraps the config so next-intl can wire up its server-side
// request config (i18n/request.ts) and message imports without the
// "Couldn't find next-intl config" runtime error (#1260).
const withNextIntl = createNextIntlPlugin("./i18n/request.ts");

// `withSentryConfig` is the outermost wrapper so it sees the final config,
// including next-intl's additions, when it adds its Turbopack settings and
// build hook. Wrapping order: Sentry(next-intl(nextConfig)).
//
// Key options:
//   silent           - suppresses Sentry CLI output during `next build`.
//   sourcemaps.deleteSourcemapsAfterUpload
//                    - strips source maps from the build output after they are
//                      uploaded so they are not served publicly. Defaults to
//                      true in v10; set explicitly for clarity.
//   widenClientFileUpload - disabled; we do not need to upload additional
//                      client files beyond the standard Next.js output.
//   tunnelRoute      - proxies Sentry events through /monitoring so ad-blocker
//                      extensions cannot block the DSN endpoint. Serwist
//                      runtimeCaching only intercepts GET requests, so POST
//                      requests to /monitoring bypass the service-worker cache
//                      matcher entirely and reach the server unaltered.
//   org / project    - read from env; build-time only (not shipped to browser).
//
// BUNDLER: the build uses Turbopack, which is what a plain `next build` runs on
// Next 16 (package.json passes no `--webpack` flag). Under Turbopack,
// withSentryConfig uploads source maps from a
// `compiler.runAfterProductionCompile` hook that it installs by default, so no
// webpack plugin is involved; the upload runs only when SENTRY_AUTH_TOKEN is
// set (see below). Options under the `webpack` key of the Sentry options do
// nothing under this build and nothing warns about them, so do not add any:
// use a Turbopack-aware Sentry option or `nextConfig` instead.
// lib/observability/nextConfigSentry.test.ts fails if one is added.
//
// DEBUG LOGGING: the Sentry SDK's debug-logging code still ships in the
// bundle. `webpack.treeshake.removeDebugLogging` was removed because it did
// nothing under Turbopack (#2076), and @sentry/nextjs still has no Turbopack
// equivalent as of 11.1.0 (`treeshake.removeDebugLogging` is only read by its
// webpack config; re-check when upgrading it): Sentry's tree-shaking
// guide says those options are not supported for Turbopack builds. Defining `__SENTRY_DEBUG__` through `compiler.define`
// is not a proven substitute, because the SDK checks
// `typeof __SENTRY_DEBUG__`, and it is unconfirmed whether Turbopack rewrites a
// `typeof` check for a user define. The code only logs when `debug: true` is
// passed to Sentry.init, which no instrumentation file does, so today the cost
// is bundle size only.
//
// INERT WITHOUT SECRETS: When NEXT_PUBLIC_SENTRY_DSN is not set, Sentry.init
// is a no-op (no network, no throw). When SENTRY_AUTH_TOKEN is absent,
// withSentryConfig warns and skips map upload - it does NOT fail the build.
export default withSentryConfig(withNextIntl(nextConfig), {
  silent: true,
  sourcemaps: {
    deleteSourcemapsAfterUpload: true,
  },
  widenClientFileUpload: false,
  tunnelRoute: "/monitoring",
  org: process.env.SENTRY_ORG,
  project: process.env.SENTRY_PROJECT,
});
